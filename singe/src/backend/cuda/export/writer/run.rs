// A command that runs a program once with nothing of Singe: it reads each input from a file, runs the program, and writes each output to a file.

use crate::{
    backend::cuda::{
        export::{builder::span_bytes, writer::Renderer},
        kernel_plan::value_type,
    },
    error::Result,
    utility::emit,
};

impl Renderer<'_> {
    // The runner of a program exported without a page layout, or `None` for a decoder's step, which its generation loop runs instead.
    pub fn runner(&self, weights_bytes: usize) -> Result<Option<String>> {
        if self.program.decoding.is_some() {
            return Ok(None);
        }

        let prefix = self.prefix;
        let program = self.program;
        let (inputs, outputs) = (program.inputs.len(), program.outputs.len());
        let mut code = String::new();
        for (index, value) in program.inputs.iter().enumerate() {
            let bytes = span_bytes(value.data_type, &value.layout)?;
            let ty = value_type(value.data_type)?;
            let qualifier = if value.written { "" } else { "const " };
            emit!(
                code,
                "    void* input_{index} = device_zeroed({bytes}ULL);\n    {{\n        const std::vector<char> contents = read_file(argv[{argument}], {bytes}ULL);\n        check_cuda(cudaMemcpy(input_{index}, contents.data(), contents.size(), cudaMemcpyHostToDevice), \"cudaMemcpy\");\n    }}\n    inputs.{name} = static_cast<{qualifier}{ty}*>(input_{index});",
                argument = index + 1,
                name = value.name,
            );
        }

        for (index, value) in program.outputs.iter().enumerate() {
            let bytes = span_bytes(value.data_type, &value.layout)?;
            let ty = value_type(value.data_type)?;
            emit!(
                code,
                "    void* output_{index} = device_zeroed({bytes}ULL);\n    outputs.{name} = static_cast<{ty}*>(output_{index});",
                name = value.name,
            );
        }

        let mut written = String::new();
        let mut frees = String::new();
        for (index, value) in program.outputs.iter().enumerate() {
            let bytes = span_bytes(value.data_type, &value.layout)?;
            emit!(
                written,
                "    write_file(argv[{argument}], output_{index}, {bytes}ULL);",
                argument = inputs + index + 1,
            );
            emit!(frees, "    cudaFree(output_{index});");
        }

        for index in 0..inputs {
            emit!(frees, "    cudaFree(input_{index});");
        }

        let usage = (0..inputs)
            .map(|index| format!("INPUT{index}"))
            .chain((0..outputs).map(|index| format!("OUTPUT{index}")))
            .collect::<Vec<_>>()
            .join(" ");
        let weights = if weights_bytes == 0 {
            "    const std::vector<char> weights;\n".to_owned()
        } else {
            format!(
                "    const std::vector<char> weights = read_file(\"{prefix}.weights\", {weights_bytes}ULL);\n"
            )
        };
        Ok(Some(format!(
            "// Generated by Singe.\n// Runs `{prefix}.h` once with nothing else: `{prefix}_run {usage}` beside `{prefix}.weights`, reading each input's bytes from its file and writing each output's bytes to its file, in the order `{prefix}.json` lists them.\n#include <cuda_runtime.h>\n#include <stdio.h>\n#include <stdlib.h>\n\n#include <vector>\n\n#include \"{prefix}.h\"\n\nstatic void check(int status, const char* what) {{\n    if (status != 0) {{\n        fprintf(stderr, \"%s returned %d: %s\\n\", what, status, {prefix}_failure());\n        exit(1);\n    }}\n}}\n\nstatic void check_cuda(cudaError_t status, const char* what) {{\n    if (status != cudaSuccess) {{\n        fprintf(stderr, \"%s failed: %s\\n\", what, cudaGetErrorString(status));\n        exit(1);\n    }}\n}}\n\nstatic void* device_zeroed(unsigned long long bytes) {{\n    void* pointer = nullptr;\n    if (bytes > 0) {{\n        check_cuda(cudaMalloc(&pointer, bytes), \"cudaMalloc\");\n        check_cuda(cudaMemset(pointer, 0, bytes), \"cudaMemset\");\n    }}\n    return pointer;\n}}\n\nstatic std::vector<char> read_file(const char* path, unsigned long long bytes) {{\n    std::vector<char> contents(bytes);\n    FILE* file = fopen(path, \"rb\");\n    if (file == nullptr || fread(contents.data(), 1, bytes, file) != bytes) {{\n        fprintf(stderr, \"cannot read %llu bytes from %s\\n\", bytes, path);\n        exit(1);\n    }}\n    fclose(file);\n    return contents;\n}}\n\nstatic void write_file(const char* path, const void* buffer, unsigned long long bytes) {{\n    std::vector<char> contents(bytes);\n    check_cuda(cudaMemcpy(contents.data(), buffer, bytes, cudaMemcpyDeviceToHost), \"cudaMemcpy\");\n    FILE* file = fopen(path, \"wb\");\n    if (file == nullptr || fwrite(contents.data(), 1, bytes, file) != bytes) {{\n        fprintf(stderr, \"cannot write %llu bytes to %s\\n\", bytes, path);\n        exit(1);\n    }}\n    fclose(file);\n}}\n\nint main(int argc, char** argv) {{\n    if (argc != {arguments}) {{\n        fprintf(stderr, \"usage: %s {usage}\\n\", argv[0]);\n        return 2;\n    }}\n{weights}    {prefix}_state* state = nullptr;\n    check({prefix}_create(&state), \"{prefix}_create\");\n    check({prefix}_load_weights(state, weights.empty() ? nullptr : weights.data()), \"{prefix}_load_weights\");\n    {prefix}_inputs inputs;\n    {prefix}_outputs outputs;\n{code}\n    check({prefix}_run(state, &inputs, &outputs, nullptr), \"{prefix}_run\");\n    unsigned int word = 0;\n    check({prefix}_finish(state, nullptr, &word), \"{prefix}_finish\");\n    if (word != 0) {{\n        fprintf(stderr, \"a checking kernel reported %u\\n\", word);\n        return 1;\n    }}\n{written}\n    {prefix}_destroy(state);\n{frees}\n    return 0;\n}}\n",
            arguments = inputs + outputs + 1,
        )))
    }
}
