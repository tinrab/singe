// A name C++ accepts, unique among `taken`.
pub fn identifier(name: &str, taken: &mut HashSet<String>) -> String {
    let mut base = name
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '_' {
                character
            } else {
                '_'
            }
        })
        .collect::<String>();
    if base.is_empty() || base.starts_with(|character: char| character.is_ascii_digit()) {
        base.insert(0, '_');
    }

    if CPP_KEYWORDS.contains(&base.as_str()) {
        base.push('_');
    }

    let mut unique = base.clone();
    let mut suffix = 1;
    while !taken.insert(unique.clone()) {
        unique = format!("{base}_{suffix}");
        suffix += 1;
    }
    unique
}
