use crate::backend::registry::{
    BackendExecution, operation_schema, operation_support, registered_operations,
};

/// Returns a Markdown table of the dtypes, CUDA graph providers, and layout support of every built-in operation.
#[must_use]
pub fn operation_support_table() -> String {
    let mut table = String::from(
        "# Operation support\n\n\
         Generated by `cargo run -q -p singe --no-default-features --example operation_support`.\n\n\
         These are registry encoding limits. Operand roles, promotion, attributes, layouts, and hardware/provider preparation further constrain a request.\n\n\
         Each execution column lists input encodings followed by result encodings. Provider names describe available CUDA lowering implementations, not a guarantee for every listed dtype and geometry.\n\n\
         | Operation | CPU eager input → output | CUDA eager input → output | CUDA graph input → output | CUDA graph providers | Layout |\n\
         | --- | --- | --- | --- | --- | --- |\n",
    );
    let rows = registered_operations().iter().map(|&operation| {
        let support = operation_support(operation);
        let schema = operation_schema(operation);
        let columns = [
            BackendExecution::CpuEager,
            BackendExecution::CudaEager,
            BackendExecution::CudaGraph,
        ]
        .map(|execution| {
            let output = if support.supports(execution) && schema.output_count() > 1 {
                schema
                    .output_roles()
                    .iter()
                    .map(|role| {
                        let data_types = support
                            .data_types(execution)
                            .iter()
                            .map(|data_type| format!("{:?}", role.data_type(*data_type)))
                            .collect::<Vec<_>>()
                            .join(", ");
                        format!("{role:?}: {data_types}")
                    })
                    .collect::<Vec<_>>()
                    .join(", ")
            } else {
                support.data_type_list(execution)
            };
            format!("{} → {}", support.input_data_type_list(execution), output)
        });
        format!(
            "| {} | {} | {} | {} | {} | {} |\n",
            operation.name(),
            columns[0],
            columns[1],
            columns[2],
            support.provider_list(),
            support.layout_name()
        )
    });
    table.extend(rows);
    table
}
