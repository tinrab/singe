fn render_selection_entries(dtype: Dtype) -> String {
    let ty = ty(dtype.name);
    let zero = expr(dtype.zero);
    let clamp = format_ident!("clamp_{}", dtype.name);
    let lerp = format_ident!("lerp_{}", dtype.name);
    let where_name = format_ident!("where_{}", dtype.name);
    let where_bool = format_ident!("where_bool_{}", dtype.name);
    let masked_fill = format_ident!("masked_fill_{}", dtype.name);
    render_items(quote! {
        #[cutile::entry()]
        pub fn #clamp<const B: i32>(
            out: &mut Tensor<#ty, { [B] }>,
            input: &Tensor<#ty, { [-1] }>,
            min_value: #ty,
            max_value: #ty,
        ) {
            let x: Tile<#ty, { [B] }> = load_tile_like(input, out);
            let min_value = broadcast_scalar(min_value, out.shape());
            let max_value = broadcast_scalar(max_value, out.shape());
            out.store(min_tile(max_tile(x, min_value), max_value));
        }

        #[cutile::entry()]
        pub fn #lerp<const B: i32>(
            out: &mut Tensor<#ty, { [B] }>,
            lhs: &Tensor<#ty, { [-1] }>,
            rhs: &Tensor<#ty, { [-1] }>,
            scalar: #ty,
        ) {
            let lhs_tile: Tile<#ty, { [B] }> = load_tile_like(lhs, out);
            let rhs_tile: Tile<#ty, { [B] }> = load_tile_like(rhs, out);
            let scalar = broadcast_scalar(scalar, out.shape());
            out.store(lhs_tile + scalar * (rhs_tile - lhs_tile));
        }

        #[cutile::entry()]
        pub fn #where_name<const B: i32>(
            out: &mut Tensor<#ty, { [B] }>,
            condition: &Tensor<#ty, { [-1] }>,
            x: &Tensor<#ty, { [-1] }>,
            y: &Tensor<#ty, { [-1] }>,
        ) {
            let condition_tile: Tile<#ty, { [B] }> = load_tile_like(condition, out);
            let x_tile: Tile<#ty, { [B] }> = load_tile_like(x, out);
            let y_tile: Tile<#ty, { [B] }> = load_tile_like(y, out);
            let zero = constant(#zero, out.shape());
            let mask = cmpf(
                condition_tile,
                zero,
                predicate::NotEqual,
                cmp_ordering::Ordered,
            );
            out.store(select(mask, x_tile, y_tile));
        }

        #[cutile::entry()]
        pub fn #where_bool<const B: i32>(
            out: &mut Tensor<#ty, { [B] }>,
            condition: &Tensor<u8, { [-1] }>,
            x: &Tensor<#ty, { [-1] }>,
            y: &Tensor<#ty, { [-1] }>,
        ) {
            let condition_tile: Tile<u8, { [B] }> = load_tile_like(condition, out);
            let x_tile: Tile<#ty, { [B] }> = load_tile_like(x, out);
            let y_tile: Tile<#ty, { [B] }> = load_tile_like(y, out);
            let zero = constant(0u8, out.shape());
            let mask = cmpi(condition_tile, zero, predicate::NotEqual);
            out.store(select(mask, x_tile, y_tile));
        }

        #[cutile::entry()]
        pub fn #masked_fill<const B: i32>(
            out: &mut Tensor<#ty, { [B] }>,
            input: &Tensor<#ty, { [-1] }>,
            mask: &Tensor<u8, { [-1] }>,
            value: #ty,
        ) {
            let input_tile: Tile<#ty, { [B] }> = load_tile_like(input, out);
            let mask_tile: Tile<u8, { [B] }> = load_tile_like(mask, out);
            let zero = constant(0u8, out.shape());
            let mask = cmpi(mask_tile, zero, predicate::NotEqual);
            let value = broadcast_scalar(value, out.shape());
            out.store(select(mask, value, input_tile));
        }
    })
}

