pub fn generate_cutile_dtype_kernels() -> Result<()> {
    let root = workspace_root()?;
    for &dtype in DTYPES {
        let dir = root.join(format!("singe-kernel/src/-generated/cutile/{}", dtype.name));
        update_dtype_files(&dir, dtype)?;
    }
    Ok(())
}

#[derive(Clone, Copy)]
