fn push_unary_param_entry(out: &mut String, dtype: Dtype, name: &str, param: &str, _unused: bool) {
    let ty = ty(dtype.name);
    let zero = expr(dtype.zero);
    let one = expr(dtype.one);
    let body = match name {
        "leaky_relu" => quote! {
            let x: Tile<#ty, { [B] }> = load_tile_like(input, out);
            let zero = constant(#zero, out.shape());
            let positive = cmpf(
                x,
                zero,
                predicate::GreaterThanOrEqual,
                cmp_ordering::Ordered,
            );
            out.store(select(
                positive,
                x,
                x * broadcast_scalar(negative_slope, out.shape()),
            ));
        },
        "elu" => quote! {
            let x: Tile<#ty, { [B] }> = load_tile_like(input, out);
            let zero = constant(#zero, out.shape());
            let one = constant(#one, out.shape());
            let positive = cmpf(
                x,
                zero,
                predicate::GreaterThanOrEqual,
                cmp_ordering::Ordered,
            );
            out.store(select(
                positive,
                x,
                broadcast_scalar(alpha, out.shape()) * (exp(x) - one),
            ));
        },
        "celu" => quote! {
            let x: Tile<#ty, { [B] }> = load_tile_like(input, out);
            let zero = constant(#zero, out.shape());
            let one = constant(#one, out.shape());
            let alpha = broadcast_scalar(alpha, out.shape());
            let positive = cmpf(
                x,
                zero,
                predicate::GreaterThanOrEqual,
                cmp_ordering::Ordered,
            );
            out.store(select(positive, x, alpha * (exp(x / alpha) - one)));
        },
        "hardshrink" => quote! {
            let x: Tile<#ty, { [B] }> = load_tile_like(input, out);
            let zero = constant(#zero, out.shape());
            let lambda = broadcast_scalar(lambda, out.shape());
            let keep_positive = cmpf(x, lambda, predicate::GreaterThan, cmp_ordering::Ordered);
            let keep_negative = cmpf(x, zero - lambda, predicate::LessThan, cmp_ordering::Ordered);
            out.store(select(keep_positive | keep_negative, x, zero));
        },
        "softshrink" => quote! {
            let x: Tile<#ty, { [B] }> = load_tile_like(input, out);
            let zero = constant(#zero, out.shape());
            let lambda = broadcast_scalar(lambda, out.shape());
            let positive = cmpf(x, lambda, predicate::GreaterThan, cmp_ordering::Ordered);
            let negative = cmpf(x, zero - lambda, predicate::LessThan, cmp_ordering::Ordered);
            out.store(select(
                positive,
                x - lambda,
                select(negative, x + lambda, zero),
            ));
        },
        _ => unreachable!(),
    };
    let param = if name == "leaky_relu" {
        "negative_slope"
    } else if matches!(name, "hardshrink" | "softshrink") {
        "lambda"
    } else {
        param
    };
    let name = format_ident!("{name}_{}", dtype.name);
    let param = format_ident!("{param}");
    out.push_str(&render_items(quote! {
        #[cutile::entry()]
        pub fn #name<const B: i32>(
            out: &mut Tensor<#ty, { [B] }>,
            input: &Tensor<#ty, { [-1] }>,
            #param: #ty,
        ) {
            #body
        }
    }));
}

