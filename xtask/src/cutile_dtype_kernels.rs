fn update_dtype_files(dir: &Path, dtype: Dtype) -> Result<()> {
    let mut elementwise = render_elementwise_entries(dtype);
    elementwise.push_str(&render_selection_entries(dtype));
    let mut reduction = render_reduction_entries(dtype);
    reduction.push_str(&render_arg_reduction_entries(dtype));
    write_generated_file(
        &dir.join("elementwise.rs"),
        render_kernel_file(
            dtype,
            elementwise,
            &["binary_store", "cmp_store", "cmp_bool_store"],
            &[],
        )?,
    )?;
    write_generated_file(
        &dir.join("cast.rs"),
        render_kernel_file(dtype, render_cast_entries(dtype), &[], &[])?,
    )?;
    write_generated_file(
        &dir.join("quantization.rs"),
        render_kernel_file(
            dtype,
            render_quantization_entries(dtype),
            &[],
            quantization_utility_exports(dtype),
        )?,
    )?;
    write_generated_file(
        &dir.join("activation.rs"),
        render_kernel_file(
            dtype,
            render_activation_entries(dtype),
            &["activation_unary_store"],
            &[],
        )?,
    )?;
    write_generated_file(
        &dir.join("unary.rs"),
        render_kernel_file(
            dtype,
            render_unary_entries(dtype),
            &["unary_store", "nan_to_num_store", "unary_bool_store"],
            &[],
        )?,
    )?;
    write_generated_file(
        &dir.join("scalar.rs"),
        render_kernel_file(
            dtype,
            render_scalar_entries(dtype),
            &["scalar_store", "scalar_cmp_bool_store"],
            &[],
        )?,
    )?;
    write_generated_file(
        &dir.join("softmax.rs"),
        render_kernel_file(
            dtype,
            render_softmax_entries(dtype),
            &["softmax_impl"],
            softmax_utility_exports(dtype),
        )?,
    )?;
    write_generated_file(
        &dir.join("reduction.rs"),
        render_kernel_file(dtype, reduction, &["reduce_impl", "arg_reduce_impl"], &[])?,
    )?;
    Ok(())
}

fn render_kernel_file(
    dtype: Dtype,
    entries: String,
    utility_helpers: &[&str],
    utility_exports: &[&str],
) -> Result<String> {
    let utility_path = syn::parse_str::<syn::Path>(&format!(
        "crate::cuda::cutile::kernel::{}::utility",
        dtype.name
    ))
    .expect("generated utility path must parse");
    let entry_items = syn::parse_file(&entries)
        .expect("generated cutile dtype entries must parse")
        .items;
    let mut module_items: Vec<Item> = Vec::new();
    module_items.push(syn::parse_quote!(
        use cutile::core::*;
    ));
    module_items.extend(extract_utility_helpers(dtype, utility_helpers)?);
    module_items.extend(entry_items);
    let utility_exports = utility_exports.iter().map(|export| {
        let export = format_ident!("{export}");
        quote!(pub use #utility_path::#export;)
    });
    let file = syn::parse2::<syn::File>(quote! {
        #[cutile::module]
        mod kernels {
            #(#module_items)*
        }

        pub use kernels::*;
        #(#utility_exports)*
    })
    .expect("generated cutile dtype file must parse");
    Ok(format!(
        "// @generated by cargo xtask gen-cutile-dtype-kernels\n\
         // Do not edit generated entries by hand.\n\n\
         {}",
        prettyplease::unparse(&file)
    ))
}

// We need this because cutile needs helper alongside kernels.
fn extract_utility_helpers(dtype: Dtype, helper_names: &[&str]) -> Result<Vec<Item>> {
    if helper_names.is_empty() {
        return Ok(Vec::new());
    }

    let root = workspace_root()?;
    let path = root.join(format!(
        "singe-kernel/src/cuda/cutile/kernel/{}/utility.rs",
        dtype.name
    ));
    let source = fs::read_to_string(&path)?;
    let file = syn::parse_file(&source)?;
    let names: HashSet<&str> = helper_names.iter().copied().collect();
    let module = file
        .items
        .into_iter()
        .find_map(|item| match item {
            Item::Mod(module) if module.ident == "kernels" => Some(module),
            _ => None,
        })
        .expect("cutile dtype utility file must contain kernels module");
    let items = module_items(module)
        .into_iter()
        .filter(|item| match item {
            Item::Fn(function) => names.contains(function.sig.ident.to_string().as_str()),
            _ => false,
        })
        .collect::<Vec<_>>();
    assert_eq!(
        items.len(),
        names.len(),
        "cutile dtype utility file is missing requested helpers"
    );
    Ok(items)
}

fn module_items(module: ItemMod) -> Vec<Item> {
    module
        .content
        .expect("cutile dtype utility kernels module must be inline")
        .1
}

