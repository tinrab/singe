use std::{env, fs, process};

use anyhow::{Context, Result, anyhow};
use bomboni_prost::{ApiConfig, config::CompileConfig, path_map::PathMap};
use prost_build::Config as ProstConfig;

use crate::utility::{workspace_root, write_generated_file};

const PACKAGES: &[&str] = &["onnx", "onnx_structure"];

/// Regenerates `singe-onnx/src/proto/{onnx,onnx_structure}.rs` from the crate's `.proto` files.
///
/// # Errors
///
/// Returns an error if `protoc` fails, the descriptor helpers cannot be generated, or a file cannot be read or written.
pub fn generate_onnx_proto() -> Result<()> {
    let root = workspace_root()?;
    let crate_root = root.join("singe-onnx");
    let proto_root = crate_root.join("proto");
    let proto_paths = PACKAGES
        .iter()
        .map(|package| proto_root.join(format!("{package}.proto")))
        .collect::<Vec<_>>();
    let out_dir = env::temp_dir().join(format!("singe-onnx-proto-{}", process::id()));
    fs::create_dir_all(&out_dir)
        .with_context(|| format!("failed to create {}", out_dir.display()))?;
    let descriptor_path = out_dir.join("onnx.bin");

    let mut prost_config = ProstConfig::default();
    prost_config
        .out_dir(&out_dir)
        .file_descriptor_set_path(&descriptor_path)
        .enable_type_names()
        .protoc_arg("--experimental_allow_proto3_optional");
    prost_config
        .compile_protos(&proto_paths, &[proto_root.as_path()])
        .context("failed to compile the onnx protobuf definitions")?;

    bomboni_prost::compile(CompileConfig {
        file_descriptor_set_path: descriptor_path,
        output_path: out_dir.clone(),
        format: true,
        api: ApiConfig {
            helpers_mod: Some("helpers".into()),
            serde: false,
            ..Default::default()
        },
        external_paths: PathMap::default(),
    })
    .map_err(|error| anyhow!("failed to generate the onnx protobuf helpers: {error}"))?;

    for &package in PACKAGES {
        let mut contents = format!(
            "// @generated by `cargo xtask gen-onnx-proto` from `proto/{package}.proto`; do not edit.\n\n"
        );
        for suffix in ["rs", "plus.rs"] {
            let path = out_dir.join(format!("{package}.{suffix}"));
            contents.push_str(
                &fs::read_to_string(&path)
                    .with_context(|| format!("failed to read {}", path.display()))?,
            );
        }

        write_generated_file(
            &crate_root.join(format!("src/proto/{package}.rs")),
            &contents,
        )?;
    }

    fs::remove_dir_all(&out_dir).with_context(|| format!("failed to remove {}", out_dir.display()))
}
