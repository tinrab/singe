def generate():
    assert onnx.__version__ == "1.21.0", onnx.__version__
    lines = [
        "// Generated by `just references onnx_schemas` from ONNX 1.21.0.",
        "// Do not edit.",
        "// Semantic support intervals are maintained in the generator.",
        "use singe_onnx::AttributeType;",
        "",
        "use crate::{data_type::DataType, onnx::importer::import::compatibility::OperatorSchema};",
        "",
        "pub const SCHEMAS: &[OperatorSchema] = &[",
    ]
    type_sets = {}
    for name, (minimum, maximum) in sorted(RANGES.items()):
        versions = {}
        for version in range(minimum, maximum + 1):
            schema = onnx.defs.get_schema(name, version)
            versions.setdefault(schema.since_version, []).append(version)
        for since, versions in versions.items():
            schema = onnx.defs.get_schema(name, since)
            required_inputs = [
                i
                for i, p in enumerate(schema.inputs)
                if p.option == onnx.defs.OpSchema.FormalParameterOption.Single
            ]
            required_outputs = [
                i
                for i, p in enumerate(schema.outputs)
                if p.option == onnx.defs.OpSchema.FormalParameterOption.Single
            ]
            attrs = ", ".join(
                f"({json.dumps(k)}, AttributeType::{TYPES[int(a.type)]}, {str(a.required).lower()})"
                for k, a in sorted(schema.attributes.items())
            )
            constraints = {
                c.type_param_str: c.allowed_type_strs for c in schema.type_constraints
            }
            inputs = []
            for parameter in schema.inputs:
                permitted = constraints.get(parameter.type_str, [parameter.type_str])
                dtypes = sorted(
                    {
                        rust
                        for onnx_type, rust in DTYPES.items()
                        if f"tensor({onnx_type})" in permitted
                    }
                )
                key = tuple(dtypes)
                type_name = type_sets.setdefault(key, f"TYPES_{len(type_sets)}")
                inputs.append(
                    f"({json.dumps(parameter.type_str)}, {type_name}, {str(parameter.is_homogeneous).lower()})"
                )
            lines += [
                "    OperatorSchema {",
                f'        operator: "{name}",',
                f"        min_opset: {min(versions)}, max_opset: {max(versions)}, schema_version: {since},",
                f"        input_range: ({schema.min_input:_}, {schema.max_input:_}), output_range: ({schema.min_output:_}, {schema.max_output:_}),",
                f"        required_inputs: &{required_inputs}, required_outputs: &{required_outputs},",
                f"        input_types: &[{', '.join(inputs)}],",
                f"        attributes: &[{attrs}],",
                "    },",
            ]
    lines += ["];", ""]
    constants = [
        f"const {name}: &[DataType] = &[{', '.join('DataType::' + dtype for dtype in types)}];"
        for types, name in type_sets.items()
    ]
    lines[7:7] = [line for constant in constants for line in (constant, "")]
    # Match the repository formatter so regeneration and --check are stable.
    import subprocess

    return subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input="\n".join(lines),
        text=True,
        check=True,
        capture_output=True,
    ).stdout


def tiny(output):
    (output / CATALOG).parent.mkdir(parents=True, exist_ok=True)
    (output / CATALOG).write_text(generate())
